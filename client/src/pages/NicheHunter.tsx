// ─── Approve Dialog ───────────────────────────────────────────────────────────

function ApproveDialog({
  open,
  onClose,
  onConfirm,
  isPending,
}: {
  open: boolean;
  onClose: () => void;
  onConfirm: (reason: string, tags: ApprovalTag[]) => void;
  isPending: boolean;
}) {
  const [reason, setReason] = useState("");
  const [selectedTags, setSelectedTags] = useState<ApprovalTag[]>([]);

  const toggleTag = (tag: ApprovalTag) => {
    setSelectedTags((prev) =>
      prev.includes(tag) ? prev.filter((t) => t !== tag) : [...prev, tag]
    );
  };

  const handleConfirm = () => {
    onConfirm(reason, selectedTags);
    setReason("");
    setSelectedTags([]);
  };

  return (
    <Dialog open={open} onOpenChange={(v) => !v && onClose()}>
      <DialogContent className="max-w-sm">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <CheckCircle2 className="h-4 w-4 text-green-400" />
            Approve Pattern
          </DialogTitle>
        </DialogHeader>
        <div className="flex flex-col gap-4">
          <div>
            <p className="text-xs text-muted-foreground uppercase tracking-wide mb-2">What do you like about it?</p>
            <div className="flex flex-wrap gap-1.5">
              {APPROVAL_TAGS.map((tag) => (
                <button
                  key={tag.id}
                  onClick={() => toggleTag(tag.id)}
                  className={`text-xs px-2 py-1 rounded-full border transition-colors ${
                    selectedTags.includes(tag.id)
                      ? "border-green-500 text-green-400 bg-green-500/15"
                      : "border-border text-muted-foreground hover:border-green-500/50"
                  }`}
                >
                  {tag.label}
                </button>
              ))}
            </div>
          </div>
          <div>
            <p className="text-xs text-muted-foreground uppercase tracking-wide mb-2">Optional note</p>
            <Textarea
              placeholder="e.g. Love the vintage distressed style..."
              value={reason}
              onChange={(e) => setReason(e.target.value)}
              className="text-sm h-20 resize-none"
            />
          </div>
        </div>
        <DialogFooter className="gap-2">
          <Button variant="outline" size="sm" onClick={onClose} disabled={isPending}>
            Cancel
          </Button>
          <Button
            size="sm"
            className="bg-accent text-accent-foreground hover:bg-accent/90"
            onClick={handleConfirm}
            disabled={isPending}
          >
            {isPending ? <Loader2 className="h-3.5 w-3.5 animate-spin mr-1.5" /> : <CheckCircle2 className="h-3.5 w-3.5 mr-1.5" />}
            Approve
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}

