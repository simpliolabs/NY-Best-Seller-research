// ─── Adaptation Mode Badge ────────────────────────────────────────────────────

function AdaptationModeBadge({ mode }: { mode: string | null }) {
  if (!mode) return null;

  if (mode === "edit_source" || mode === "style_reference_flagged") {
    return (
      <Badge
        variant="outline"
        className="text-[10px] px-1.5 py-0 h-5 border-amber-500/50 text-amber-400 bg-amber-500/10"
        title="Generated by editing the source Etsy image — verify style match"
      >
        <AlertTriangle className="w-2.5 h-2.5 mr-1" />
        Edit Mode — verify style
      </Badge>
    );
  }

  if (mode === "style_reference") {
    return (
      <Badge
        variant="outline"
        className="text-[10px] px-1.5 py-0 h-5 border-blue-500/50 text-blue-400 bg-blue-500/10"
        title="Generated using source image as style reference"
      >
        Style Ref
      </Badge>
    );
  }

  return (
    <Badge
      variant="outline"
      className="text-[10px] px-1.5 py-0 h-5 border-muted-foreground/30 text-muted-foreground"
      title="Generated from text prompt only (no source image)"
    >
      Prompt Only
    </Badge>
  );
}

// ─── Signal Chips (read-only, shown on approved/dismissed cards) ──────────────

function SignalChips({
  tags,
  type,
}: {
  tags: string[] | null;
  type: "approval" | "rejection";
}) {
  if (!tags || tags.length === 0) return null;

  const allTags = type === "approval" ? APPROVAL_TAGS : REJECTION_TAGS;
  const colorClass =
    type === "approval"
      ? "border-green-500/40 text-green-400 bg-green-500/10"
      : "border-red-500/40 text-red-400 bg-red-500/10";

  return (
    <div className="flex flex-wrap gap-1 mt-1">
      {tags.map((tag) => {
        const label = allTags.find((t) => t.id === tag)?.label ?? tag;
        return (
          <span
            key={tag}
            className={`text-[10px] px-1.5 py-0.5 rounded border ${colorClass}`}
          >
            {label}
          </span>
        );
      })}
    </div>
  );
}

