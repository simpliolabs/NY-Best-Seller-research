// ─── Main Page ────────────────────────────────────────────────────────────────

export default function NicheHunter() {
  const { activeWorkspace } = useWorkspace();
  const workspaceId = activeWorkspace?.id ?? "";

  const [activeScanId, setActiveScanId] = useState<string | null>(null);
  const [actingPatternId, setActingPatternId] = useState<string | null>(null);
  const [statusFilter, setStatusFilter] = useState<"discovered" | "approved" | "dismissed" | undefined>(undefined);

  // Signal dialog state
  const [approveDialogPatternId, setApproveDialogPatternId] = useState<string | null>(null);
  const [dismissDialogPatternId, setDismissDialogPatternId] = useState<string | null>(null);

  const utils = trpc.useUtils();

  const { data: scanStatus } = trpc.nicheHunter.getScanStatus.useQuery(
    { scanId: activeScanId ?? undefined, workspaceId },
    {
      enabled: !!workspaceId,
      refetchInterval: (query) => {
        const status = query.state.data?.status;
        return status === "running" ? 2000 : false;
      },
    }
  );

  useEffect(() => {
    if (scanStatus?.scanId && !activeScanId) {
      setActiveScanId(scanStatus.scanId);
    }
  }, [scanStatus?.scanId, activeScanId]);

  useEffect(() => {
    if (scanStatus?.status === "completed") {
      utils.nicheHunter.getPatterns.invalidate({ workspaceId });
    }
  }, [scanStatus?.status, workspaceId, utils]);

  const { data: patterns = [], isLoading: patternsLoading } =
    trpc.nicheHunter.getPatterns.useQuery(
      { workspaceId, status: statusFilter },
      { enabled: !!workspaceId }
    );

  const triggerScan = trpc.nicheHunter.triggerScan.useMutation({
    onSuccess: (data) => {
      if (data.alreadyRunning) {
        toast.info("A scan is already running.");
      } else {
        setActiveScanId(data.scanId);
        toast.success("Scan started! Patterns will appear below as they are discovered.");
      }
    },
    onError: (err) => toast.error(err.message),
  });

  const approvePattern = trpc.nicheHunter.approvePattern.useMutation({
    onMutate: ({ patternId }) => setActingPatternId(patternId),
    onSuccess: () => {
      utils.nicheHunter.getPatterns.invalidate({ workspaceId });
      utils.nicheHunter.getStylePreferences.invalidate({ workspaceId });
      utils.library.list.invalidate();
      setApproveDialogPatternId(null);
      toast.success("Pattern approved! Next: Generate images in the Library, then refine in Design Studio.", {
        duration: 6000,
        action: {
          label: "Go to Library →",
          onClick: () => window.location.assign(`/${activeWorkspace?.slug}/library`),
        },
      });
    },
    onError: (err) => toast.error(err.message),
    onSettled: () => setActingPatternId(null),
  });

  const dismissPattern = trpc.nicheHunter.dismissPattern.useMutation({
    onMutate: ({ patternId }) => setActingPatternId(patternId),
    onSuccess: () => {
      utils.nicheHunter.getPatterns.invalidate({ workspaceId });
      utils.nicheHunter.getStylePreferences.invalidate({ workspaceId });
      setDismissDialogPatternId(null);
      toast.success("Pattern dismissed.");
    },
    onError: (err) => toast.error(err.message),
    onSettled: () => setActingPatternId(null),
  });

  const flagEditMode = trpc.nicheHunter.flagEditModeResult.useMutation({
    onSuccess: () => {
      utils.nicheHunter.getPatterns.invalidate({ workspaceId });
      toast.info("Flagged for style-reference retry. The system will use this signal in future scans.");
    },
    onError: (err) => toast.error(err.message),
  });

  if (!activeWorkspace) {
    return (
      <div className="flex items-center justify-center h-64 text-muted-foreground">
        Loading workspace...
      </div>
    );
  }

  if (activeWorkspace.workspaceType !== "niche_hunter") {
    return (
      <div className="flex items-center justify-center h-64 text-muted-foreground">
        Niche Hunter is only available for Niche Hunter workspaces.
      </div>
    );
  }

  const isScanning = scanStatus?.status === "running";
  const discoveredCount = patterns.filter((p) => p.status === "discovered").length;
  const approvedCount = patterns.filter((p) => p.status === "approved").length;

  return (
    <div className="flex flex-col gap-6 p-6">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div>
          <h1 className="text-2xl font-semibold flex items-center gap-2">
            <Crosshair className="h-6 w-6 text-accent" />
            Niche Hunter
          </h1>
          <p className="text-sm text-muted-foreground mt-1">
            Discover transferable design patterns from hot-selling listings and adapt them for{" "}
            <span className="text-foreground font-medium">{activeWorkspace.name}</span>.
          </p>
        </div>
        <Button
          onClick={() => triggerScan.mutate({ workspaceId })}
          disabled={isScanning || triggerScan.isPending}
          className="bg-accent text-accent-foreground hover:bg-accent/90"
        >
          {isScanning || triggerScan.isPending ? (
            <>
              <Loader2 className="h-4 w-4 mr-2 animate-spin" />
              Scanning...
            </>
          ) : (
            <>
              <Zap className="h-4 w-4 mr-2" />
              Run Scan
            </>
          )}
        </Button>
      </div>

      {/* Style Preferences card — shown once enough signals exist */}
      <StylePreferencesCard workspaceId={workspaceId} />

      {/* Scan progress */}
      {scanStatus && scanStatus.status !== "none" && (
        <Card className="border border-border">
          <CardContent className="pt-4 pb-4">
            <div className="flex items-center justify-between mb-2">
              <span className="text-sm font-medium">
                {scanStatus.status === "running"
                  ? "Scan in progress..."
                  : scanStatus.status === "completed"
                    ? `Scan complete — ${scanStatus.patternsFound} patterns found`
                    : "Scan failed"}
              </span>
              <span className="text-xs text-muted-foreground">{scanStatus.progress}%</span>
            </div>
            <Progress value={scanStatus.progress} className="h-2" />
            {scanStatus.status === "failed" && scanStatus.errorLog && (
              <p className="text-xs text-destructive mt-2">{scanStatus.errorLog}</p>
            )}
          </CardContent>
        </Card>
      )}

      {/* Stats row */}
      {patterns.length > 0 && (
        <div className="grid grid-cols-3 gap-3">
          {[
            { label: "Discovered", count: discoveredCount, color: "#F59E0B" },
            { label: "Approved", count: approvedCount, color: "#22C55E" },
            { label: "Dismissed", count: patterns.filter((p) => p.status === "dismissed").length, color: "#EF4444" },
          ].map(({ label, count, color }) => (
            <Card
              key={label}
              className="border border-border cursor-pointer hover:border-accent/50 transition-colors"
              onClick={() =>
                setStatusFilter(
                  statusFilter === label.toLowerCase() as typeof statusFilter
                    ? undefined
                    : label.toLowerCase() as typeof statusFilter
                )
              }
            >
              <CardContent className="pt-4 pb-4 text-center">
                <p className="text-2xl font-bold tabular-nums" style={{ color }}>{count}</p>
                <p className="text-xs text-muted-foreground uppercase tracking-wide mt-1">{label}</p>
              </CardContent>
            </Card>
          ))}
        </div>
      )}

      {/* Filter bar */}
      {patterns.length > 0 && (
        <div className="flex items-center gap-2">
          <span className="text-xs text-muted-foreground">Filter:</span>
          {(["discovered", "approved", "dismissed"] as const).map((f) => (
            <Button
              key={f}
              size="sm"
              variant={statusFilter === f ? "default" : "outline"}
              className="text-xs h-7 px-3"
              onClick={() => setStatusFilter(statusFilter === f ? undefined : f)}
            >
              {f.charAt(0).toUpperCase() + f.slice(1)}
            </Button>
          ))}
          {statusFilter && (
            <Button
              size="sm"
              variant="ghost"
              className="text-xs h-7 px-2"
              onClick={() => setStatusFilter(undefined)}
            >
              <RefreshCw className="h-3 w-3 mr-1" />
              Clear
            </Button>
          )}
        </div>
      )}

      {/* Pattern grid */}
      {patternsLoading ? (
        <div className="flex items-center justify-center h-32 text-muted-foreground">
          <Loader2 className="h-5 w-5 animate-spin mr-2" />
          Loading patterns...
        </div>
      ) : patterns.length === 0 ? (
        <div className="flex flex-col items-center justify-center h-48 text-center gap-3">
          <Crosshair className="h-10 w-10 text-muted-foreground/40" />
          <p className="text-muted-foreground text-sm">
            No patterns yet. Run a scan to discover transferable design patterns.
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 xl:grid-cols-3 gap-4">
          {[...patterns]
            .filter((p) => statusFilter === "dismissed" ? p.status === "dismissed" : p.status !== "dismissed")
            .sort((a, b) => (b.score ?? 0) - (a.score ?? 0))
            .map((p) => (
              <PatternCard
                key={p.id}
                pattern={p as Pattern}
                onApprove={(id) => setApproveDialogPatternId(id)}
                onDismiss={(id) => setDismissDialogPatternId(id)}
                onFlagEditMode={(id) => flagEditMode.mutate({ patternId: id, workspaceId })}
                isActing={actingPatternId === p.id}
              />
            ))}
        </div>
      )}

      {/* Approve dialog */}
      <ApproveDialog
        open={!!approveDialogPatternId}
        onClose={() => setApproveDialogPatternId(null)}
        onConfirm={(reason, tags) => {
          if (!approveDialogPatternId) return;
          approvePattern.mutate({
            patternId: approveDialogPatternId,
            workspaceId,
            reason: reason || undefined,
            tags,
          });
        }}
        isPending={approvePattern.isPending}
      />

      {/* Dismiss dialog */}
      <DismissDialog
        open={!!dismissDialogPatternId}
        onClose={() => setDismissDialogPatternId(null)}
        onConfirm={(reason, tags) => {
          if (!dismissDialogPatternId) return;
          dismissPattern.mutate({
            patternId: dismissDialogPatternId,
            reason: reason || undefined,
            tags,
          });
        }}
        isPending={dismissPattern.isPending}
      />
    </div>
  );
}
